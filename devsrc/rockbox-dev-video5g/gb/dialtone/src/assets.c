static uint8_t shade_bits(char c) {
    switch (c) {
        case '+': return 1u;
        case '*': return 2u;
        case '#': return 3u;
        default: return 0u;
    }
}

static void encode_tile(uint8_t *dst, const char *const rows[8]) {
    uint8_t y;
    uint8_t x;

    for (y = 0u; y != 8u; ++y) {
        uint8_t lo = 0u;
        uint8_t hi = 0u;
        for (x = 0u; x != 8u; ++x) {
            uint8_t shade = shade_bits(rows[y][x]);
            lo <<= 1;
            hi <<= 1;
            lo |= (shade & 1u);
            hi |= (shade >> 1);
        }
        dst[y * 2u] = lo;
        dst[y * 2u + 1u] = hi;
    }
}

void dt_init_assets(void) BANKED {
    uint8_t i;

    for (i = 0u; i != BG_TILE_COUNT; ++i) {
        encode_tile(&bg_tiles[i * 16u], bg_patterns[i]);
    }
    for (i = 0u; i != APARTMENT_DECOR_TILE_COUNT; ++i) {
        encode_tile(&apartment_decor_tiles[i * 16u], bg_patterns[apartment_decor_sources[i]]);
    }
    for (i = 0u; i != SPRITE_TILE_COUNT; ++i) {
        encode_tile(&sprite_tiles[i * 16u], sprite_patterns[i]);
    }
}
